export function buildAcmeInsights(report: CallReport): Insight[] {
  return [
    ...report.customerTruth.map((item) => ({
      id: item.id,
      type: "CUSTOMER_FACT" as const,
      title: item.title,
      summary: item.summary,
      evidenceStatus: item.evidenceStatus,
      evidence: item.evidence,
    })),
    ...report.objections.map((item) => ({
      id: item.id,
      type: "OBJECTION" as const,
      title: item.title,
      summary: item.summary,
      severity: item.severity,
      evidenceStatus: "SUPPORTED" as const,
      evidence: item.evidence,
    })),
    ...report.risks.map((item) => ({
      id: item.id,
      type: "DEAL_RISK" as const,
      title: item.title,
      summary: item.summary,
      severity: item.severity,
      evidenceStatus: item.evidenceStatus,
      evidence: item.evidence,
    })),
    ...report.realityChecks.map((item) => ({
      id: item.id,
      type: "REALITY_CHECK" as const,
      title: item.title,
      summary: item.reason,
      severity: item.severity,
      evidenceStatus: "SUPPORTED" as const,
      evidence: item.customerEvidence,
    })),
  ];
}

